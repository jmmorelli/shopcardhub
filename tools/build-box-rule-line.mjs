#!/usr/bin/env node
// build-box-rule-line.mjs — Q-027 (Build Loop, Nov 26 2026; LEDGER O-102, O-67 follow-up).
//
// Two page-owned Bowman guides print an Oct 20 hobby-box median taken before the sport title rule (RULE_FROM.sport,
// Nov 19, tools/lib/sealed-title-rule.mjs). This tool prints, beside that older figure, the newest read in data/boxes.json,
// which was taken with the rule: median, n, window and read date, all from the file. It never edits the older figure
// and types no number: a row with fewer than 5 sales (the file's own floor) prints "not enough dated sales yet".
//
// Contract: machine-owned between BOXRULE markers. The first run places the block right after the paragraph that
// holds `after`; later runs rewrite it in place. Usage: node tools/build-box-rule-line.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { checkSealedTitleRule } from "./lib/sealed-title-rule.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const START = "<!-- BOXRULE:START";
const END = "<!-- BOXRULE:END -->";

const PAGES = [
  { page: "bowman-chrome-baseball-2026.html", anchor: "bowman-chrome-baseball", format: "hobby", after: "at a median of $509.99" },
  { page: "bowman-football.html", anchor: "bowman-football", format: "hobby", after: "Hobby is the only format with enough sales to read." },
];

const MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const md = (d) => { const [, m, day] = d.split("-"); return MON[+m - 1] + " " + +day; };
const money = (v) => "$" + Number(v).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const boxes = JSON.parse(fs.readFileSync(path.join(REPO, "data/boxes.json"), "utf8"));
const rule = checkSealedTitleRule(boxes, "data/boxes.json", "sport", { repo: REPO });
if (!rule.ok) { console.error("build-box-rule-line: data/boxes.json fails the sport title rule (" + rule.why + "); nothing written"); process.exit(1); }

let changed = 0;
for (const cfg of PAGES) {
  const file = path.join(REPO, cfg.page);
  const html = fs.readFileSync(file, "utf8");
  const row = boxes.rows.find((r) => r.anchor === cfg.anchor && r.format === cfg.format);
  if (!row) { console.error(`build-box-rule-line: no ${cfg.anchor}/${cfg.format} row in data/boxes.json; ${cfg.page} skipped`); continue; }
  const s = row.sold || {};
  const yr = (s.to || s.read || "").slice(0, 4);
  const lead = s.median != null && s.n >= 5
    ? `Newer read, with our title rule: <strong>${money(s.median)} median</strong> of ${s.n} single hobby-box sales, ${md(s.from)} – ${md(s.to)}, ${yr} (${s.source}, read ${md(s.read)}, ${s.read.slice(0, 4)}).`
    : `Newer read, with our title rule: not enough dated sales yet (fewer than 5 single hobby-box sales${s.read ? `, read ${md(s.read)}, ${s.read.slice(0, 4)}` : ""}).`;
  const body = `${lead} A sale counts only when its listing title names the product and the sport; lots, cases, breaks, packs and presales are left out. The figure above is the older read, taken before that rule. All boxes side by side: <a href="/best-hobby-boxes-2026">best hobby boxes</a>.`;
  const block = `${START} — generated by tools/build-box-rule-line.mjs from data/boxes.json (Q-027). Do not edit by hand. -->\n    <p class="section-body box-rule" style="font-size:15px;opacity:.9">${body}</p>\n    ${END}`;
  let out;
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a >= 0 && b > a) out = html.slice(0, a) + block + html.slice(b + END.length);
  else {
    const at = html.indexOf(cfg.after);
    if (at < 0) { console.error(`build-box-rule-line: "${cfg.after}" not found in ${cfg.page}; skipped`); continue; }
    const close = html.indexOf("</p>", at);
    if (close < 0) { console.error(`build-box-rule-line: no </p> after the anchor in ${cfg.page}; skipped`); continue; }
    const cut = close + 4;
    out = html.slice(0, cut) + "\n    " + block + html.slice(cut);
  }
  if (out !== html) { changed++; if (!CHECK) fs.writeFileSync(file, out); }
  console.log(`${out !== html ? (CHECK ? "would write" : "wrote") : "unchanged"}  ${cfg.page}  ${s.median != null ? money(s.median) + " n=" + s.n + " read " + s.read : "no price"}`);
}
if (CHECK && changed) process.exit(1);
