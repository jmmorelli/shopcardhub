#!/usr/bin/env node
// build-collectors-wall.mjs — the Collectors wall on /indices (E13 "Mark Monday + Collectors wall", Mo Oct 15 2026;
// Night Crew P57, Oct 16). Every Monday after the re-mark Mo's thread asks collectors for one card from their shelf;
// each reply that names a card we index becomes a row in data/collectors-wall.json and a line here.
//
// Rewrites only between <!-- WALL:START --> and <!-- WALL:END --> in indices.html (first run inserts the block right
// under the board, before the signup capture). Run from the repo root:
//   node tools/build-collectors-wall.mjs           write indices.html
//   node tools/build-collectors-wall.mjs --check   exit 1 if indices.html is not what the data says
//
// data/collectors-wall.json: [{ handle, postUrl, card, ticker, flaggedDate, consent }]
//   handle      X handle without "@", 1–15 of A–Z a–z 0–9 _
//   postUrl     https://x.com/<handle>/status/<id> (twitter.com accepted)
//   card        our card id, e.g. "pris25-161" (must exist in data/cards/<ticker>.json)
//   ticker      e.g. "PRIS25"
//   flaggedDate YYYY-MM-DD, the day they replied
//   consent     "" until they answer "ok to quote you?" with yes → "reply-yes" (only then is the handle a link)
// Printed per row: handle · card · our dated raw mark from data/cards/<tk>.json ("no sale in 30 days" when none —
// never a blank) · "flagged <date>". Newest first, 20 rows at most. Outsiders' words and prices are never printed.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const START = "<!-- WALL:START", END = "<!-- WALL:END -->";
const MAX = 20;
const FIRST_MONDAY = "Oct 19";

const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const md = (iso) => `${MON[+iso.slice(5, 7) - 1]} ${+iso.slice(8, 10)}`;
const money = (n) => "$" + Number(n).toLocaleString("en-US", n >= 100 ? { maximumFractionDigits: 0 } : { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const rows = JSON.parse(fs.readFileSync(path.join(REPO, "data/collectors-wall.json"), "utf8"));
if (!Array.isArray(rows)) throw new Error("data/collectors-wall.json must be an array");

const cardFiles = new Map();
const cardOf = (tk, id) => {
  const k = String(tk).toLowerCase();
  if (!/^[a-z0-9]+$/.test(k)) throw new Error(`collectors-wall: bad ticker ${tk}`);
  if (!cardFiles.has(k)) {
    const f = path.join(REPO, "data/cards", k + ".json");
    if (!fs.existsSync(f)) throw new Error(`collectors-wall: no data/cards/${k}.json for ${tk}`);
    cardFiles.set(k, JSON.parse(fs.readFileSync(f, "utf8")));
  }
  const d = cardFiles.get(k);
  const c = (d.cards || []).find((x) => x.id === id);
  if (!c) throw new Error(`collectors-wall: card ${id} is not in data/cards/${k}.json`);
  return { d, c };
};

const lines = rows
  .map((r, i) => {
    const where = `data/collectors-wall.json row ${i + 1}`;
    if (!/^[A-Za-z0-9_]{1,15}$/.test(r.handle || "")) throw new Error(`${where}: handle must be 1–15 of A–Z a–z 0–9 _ (no @)`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(r.flaggedDate || "")) throw new Error(`${where}: flaggedDate must be YYYY-MM-DD`);
    const okUrl = new RegExp(`^https://(?:x|twitter)\\.com/${r.handle}/status/\\d+$`, "i").test(r.postUrl || "");
    if (!okUrl) throw new Error(`${where}: postUrl must be https://x.com/${r.handle}/status/<id>`);
    const { d, c } = cardOf(r.ticker, r.card);
    return { r, d, c };
  })
  .sort((a, b) => b.r.flaggedDate.localeCompare(a.r.flaggedDate))
  .slice(0, MAX);

const rowHtml = ({ r, d, c }) => {
  const who = r.consent === "reply-yes"
    ? `<a href="${esc(r.postUrl)}" target="_blank" rel="nofollow noopener ugc">@${esc(r.handle)}</a>`
    : `@${esc(r.handle)}`;
  const name = `${c.name}${c.num ? " #" + c.num : ""}`;
  const mark = c.raw != null && c.rawAsOf ? `${money(c.raw)} <small>raw · ${md(c.rawAsOf)} mark</small>` : `<small>no sale in 30 days</small>`;
  return `<li><span class="cw-who">${who}</span><a class="cw-card" href="/card?id=${esc(c.id)}">${esc(name)} <small>${esc(d.ticker)}</small></a><span class="cw-mark">${mark}</span><span class="cw-date">flagged ${md(r.flaggedDate)}</span></li>`;
};

const body = lines.length
  ? `<ul class="cw-list">${lines.map(rowHtml).join("")}</ul>`
  : `<p class="cw-empty">First Mark Monday is ${FIRST_MONDAY}. Reply to the thread on X with a card from your shelf and we'll put our dated mark beside it here.</p>`;

const block = `${START} — Collectors wall (E13). Generated by tools/build-collectors-wall.mjs from data/collectors-wall.json. Do not hand-edit. -->
<section class="panel cw" id="collectors-wall" style="scroll-margin-top:80px;">
<style>
.cw{padding:14px 18px;margin:18px 0}.cw h2{margin:0 0 4px}.cw .cw-sub{margin:0 0 10px;font-size:13px;color:var(--text-dim,#7a969e)}
.cw-list{list-style:none;margin:0;padding:0}.cw-list li{display:grid;grid-template-columns:minmax(90px,140px) minmax(0,1fr) auto auto;gap:4px 14px;align-items:center;padding:8px 0;border-top:1px solid var(--border,rgba(255,255,255,.08));font-size:14px}
.cw-list small{font-size:11px;color:var(--text-dim,#7a969e)}.cw-card{display:inline-flex;align-items:center;gap:6px;min-height:40px;color:var(--text-head,#e4f0f4)}
.cw-mark{font-family:var(--fm,monospace);color:var(--text-head,#e4f0f4);white-space:nowrap}.cw-date{font-family:var(--fm,monospace);font-size:11px;color:var(--text-dim,#7a969e);white-space:nowrap}
.cw-who a{display:inline-flex;align-items:center;min-height:40px}.cw-empty{margin:0;font-size:14px;color:var(--text,#c9d4da)}
@media(max-width:600px){.cw{padding:12px 14px}.cw-list li{grid-template-columns:minmax(0,1fr) auto}.cw-who{grid-column:1/-1}.cw-date{grid-column:1/-1}}
</style>
<h2>Collectors wall</h2>
<p class="cw-sub">Cards collectors picked from their own shelves on Mark Monday, with our latest dated sold mark for each.</p>
${body}
</section>
${END}`;

const file = path.join(REPO, "indices.html");
const html = fs.readFileSync(file, "utf8");
let next;
const s = html.indexOf(START);
if (s !== -1) {
  const e = html.indexOf(END, s);
  if (e === -1) throw new Error("indices.html: WALL:START without WALL:END");
  next = html.slice(0, s) + block + html.slice(e + END.length);
} else {
  const anchor = '<div id="sections"></div>';
  const i = html.indexOf(anchor);
  if (i === -1) throw new Error(`indices.html: no ${anchor} to place the wall under`);
  next = html.slice(0, i + anchor.length) + "\n" + block + html.slice(i + anchor.length);
}

if (CHECK) {
  if (next !== html) { console.error("build-collectors-wall: indices.html is stale — run node tools/build-collectors-wall.mjs"); process.exit(1); }
  console.log(`build-collectors-wall: [check] ok (${lines.length} rows)`);
} else {
  if (next !== html) fs.writeFileSync(file, next);
  console.log(`build-collectors-wall: ${next !== html ? "wrote" : "unchanged"} indices.html (${lines.length} of ${rows.length} rows${rows.length > MAX ? `, capped at ${MAX}` : ""})`);
}
