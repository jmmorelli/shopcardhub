#!/usr/bin/env node
// tools/build-home-hint.mjs — owns the home search hint (<!-- SEARCH-HINT:START --> … <!-- SEARCH-HINT:END -->) in index.html and
// home-v2.html: "Try “<example>”, “<example>” or a set name · free, no account".
//
// Q-080 (Build Loop, Nov 28 2026; CoS handoff claude/handoffs/cos-2026-11-27-lookup-path-rows-3.md N-2): the hint named
// "Charizard 1st Edition", but Base Set 1st Edition Charizard (bs1e-4) is held by Price Truth (no price in data/card-search.json),
// so the box led with a different card (Dark Charizard #4). An example is printed only if, at build time, the home box's own
// matcher (js/home-v2.js: nickname list first, then cards whose name holds every query word, priced only, first word at the
// start, own page, then price) puts the named card first with a price and no set row leads. The first candidate per slot that
// passes is printed, so "Charizard 1st Edition" comes back by itself once bs1e-4 is priced again. Names only, never a price.
// Run: node tools/build-home-hint.mjs [--check]   (wired into the nightly feed after build-home)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const PAGES = ["index.html", "home-v2.html"];

// slot → candidates in order: q is what the hint prints, id the card the first row must be.
const SLOTS = [
  [{ q: "Moonbreon", id: "evs21-215" }],
  [
    { q: "Charizard 1st Edition", id: "bs1e-4" },
    { q: "Mega Gengar ex", id: "ah26-284" },
    { q: "Umbreon VMAX", id: "evs21-215" },
  ],
];

const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));
const nk = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
const CARDS = (read("data/card-search.json").cards || []).map((c) => ({ id: c[0], t: c[1], s: c[2], p: c[3], n: nk(c[1] + " " + c[2]) }));
const SPAGE = read("js/card-pages.json").static || {};
let ALIAS = {};
try { ALIAS = read("data/search-aliases.json").aliases || {}; } catch { /* no nicknames */ }
// set rows the home box lists: D.sets in index.html's #h2-data (written by build-home), title + ticker
let SETS = [];
try {
  const m = fs.readFileSync(path.join(ROOT, "index.html"), "utf8").match(/<script[^>]*id="h2-data"[^>]*>([\s\S]*?)<\/script>/);
  SETS = ((m && JSON.parse(m[1]).sets) || []).map((x) => ({ t: x.t, n: nk(x.t + " " + x.tk) }));
} catch { /* none */ }
if (!SETS.length) console.warn("build-home-hint: no set rows read from index.html #h2-data");

function aliasCards(q) {
  q = nk(q); if (q.length < 4) return [];
  const tk = q.split(" ");
  for (const k in ALIAS) if (k === q || k.indexOf(q) === 0 || tk.includes(k)) return (ALIAS[k].ids || []).map((id) => CARDS.find((c) => c.id === id)).filter((c) => c && c.p != null);
  return [];
}
function cards(q) {
  q = nk(q); if (q.length < 2) return [];
  const tk = q.split(" ");
  return CARDS.filter((c) => c.p != null && tk.every((t) => c.n.includes(t)))
    .sort((a, b) => { const sa = nk(a.t).indexOf(tk[0]) === 0 ? 0 : 1, sb = nk(b.t).indexOf(tk[0]) === 0 ? 0 : 1, pa = SPAGE[a.id] ? 0 : 1, pb = SPAGE[b.id] ? 0 : 1; return sa - sb || pa - pb || (b.p || 0) - (a.p || 0); });
}
function setLeads(q) {
  const k = nk(q), tk = k.split(" ");
  const s = SETS.filter((x) => tk.every((t) => x.n.includes(t)));
  return s.length > 0 && nk(s[0].t).indexOf(tk[0]) >= 0;
}
function firstRow(q) { const ac = aliasCards(q); return ac.concat(cards(q).filter((x) => !ac.includes(x)))[0] || null; }
function passes(c) { if (setLeads(c.q)) return false; const r = firstRow(c.q); return !!(r && r.id === c.id && r.p != null); }

const picked = [], log = [];
for (const slot of SLOTS) {
  const hit = slot.find((c) => passes(c) && !picked.includes(c.q));
  slot.forEach((c) => log.push(`${c.q} → ${passes(c) ? "first row " + c.id : "fails (first row " + ((firstRow(c.q) || {}).id || "none") + ")"}`));
  if (hit) picked.push(hit.q);
}
const ex = picked.map((q) => `“${q}”`);
const lead = ex.length ? `Try ${ex.join(", ")} or a set name` : "Try a card or a set name";
const block = `<!-- SEARCH-HINT:START — generated by tools/build-home-hint.mjs: each example is checked against the search data at build time. Do not hand-edit. --><div class="h2-hint">${lead} · free, no account</div><!-- SEARCH-HINT:END -->`;

let changed = 0;
for (const f of PAGES) {
  const fp = path.join(ROOT, f);
  if (!fs.existsSync(fp)) continue;
  const raw = fs.readFileSync(fp, "utf8");
  const re = /<!-- SEARCH-HINT:START[\s\S]*?<!-- SEARCH-HINT:END -->/;
  let out;
  if (re.test(raw)) out = raw.replace(re, block);
  else {
    const m = raw.match(/<div class="h2-hint">[^<]*<\/div>/);
    if (!m) { console.warn(`skip ${f}: no h2-hint`); continue; }
    out = raw.replace(m[0], block);
  }
  if (out !== raw) { changed++; if (!CHECK) fs.writeFileSync(fp, out); console.log(`${CHECK ? "would update" : "updated"} ${f}`); }
}
console.log(log.join("\n"));
console.log(`build-home-hint: ${lead} · ${changed} page(s) ${CHECK ? "stale" : "changed"}`);
if (CHECK && changed) process.exit(1);
