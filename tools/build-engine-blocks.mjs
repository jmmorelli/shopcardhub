//
// Business Read Sep 8: Google indexes 3/101 pages; the /card-* chart pages were 21 near-
// duplicate ~570-word templates that Google crawled and declined, while the guide pages
// (player rookie-card pages, set guides) are what people actually land on. So every
// engine-tracked card whose watchlist entry names a host page (`slug`) now renders its
// block — nightly mark, price line, hammers, verified live listings, ★ Track — INSIDE
