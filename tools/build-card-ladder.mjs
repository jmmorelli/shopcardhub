const WOTC = new Set(["BS99", "JU99", "FO99", "TR00", "NG00", "NDC01", "NR01", "ND02"]);
const GRADES = {
  psa9: { tab: "Grade 9", title: (t) => /\bpsa\s*-?\s*9\b(?![.\d])/i.test(t) && !/\bpsa\s*-?\s*10\b/i.test(t) },
  psa10: { tab: "PSA 10", title: (t) => /\bpsa\s*-?\s*10\b/i.test(t) },
  tag10: { tab: "TAG 10", title: (t) => /\btag\b/i.test(t) },
};

// ed: true/"unl" = WOTC Unlimited (drop rows titled 1st Ed / Shadowless) · "1st" = keep only rows titled 1st Edition ·
// "shadowless" = keep only rows titled Shadowless and never 1st Edition · false = modern (no edition filter)
// opts.num = the card's printed number: a row must name it ("113/181", "#113", " 113 "); opts.siblings = numbers of other
// cards with the same name in the ticker: a row naming one of them is that card's sale (Nov 3 2026, TU19 #113 / #170).
// A number of 1 digit or "10" is too common in slab titles ("PSA 9", "PSA 10") to test either way and is skipped.
const numRe = (num) => {
  const n = String(num || "").trim();
  if (!n || /^0*([0-9]|10)$/.test(n)) return null;
  if (/^[a-z]+\s*\d+$/i.test(n)) { const m = /^([a-z]+)\s*(\d+)$/i.exec(n); return new RegExp(`\\b${m[1]}\\s?-?0*${m[2]}(?![0-9])`, "i"); }
  if (/^\d+$/.test(n)) return new RegExp(`(^|[^0-9/.$,])0*${n}(?![0-9a-z]|[.,][0-9])`, "i");   // "25th" is not card 25
  return new RegExp(`\\b${n.replace(/[^a-z0-9]/gi, "")}\\b`, "i");
};
// WOTC tickers: the 2021 Celebrations Classic Collection and other modern reprints carry the old name and number
const WOTC_REPRINT = /classic\s*coll|class\.?\s*coll|celebrations?\b|\bceleb\b|25th|\b20[12]\d\b/i;
export function numOk(t, opts) {
  if (!opts) return true;
  const own = numRe(opts.num);
  if (own && !own.test(t)) return false;
  for (const s of opts.siblings || []) { const re = numRe(s); if (re && re.test(t) && !(own && own.source === re.source)) return false; }
  return true;
}
export function ladderFromHtml(html, wotc, opts = null) {
  const tabs = [...html.matchAll(/<option[^>]*value="completed-auctions-([a-z0-9-]+)"[^>]*>([^<(]+)/g)].map((m) => ({ cls: m[1], label: m[2].trim() }));
  const out = {};
  for (const [k, g] of Object.entries(GRADES)) {
    const t = tabs.find((x) => x.label.toLowerCase() === g.tab.toLowerCase());
    if (!t) { out[k] = null; continue; }
    const rows = soldRows(html, t.cls).filter((r) => g.title(r.title) && !/\blot\b|proxy|custom|reprint/i.test(r.title) && edOk(r.title, wotc) && !(wotc && WOTC_REPRINT.test(r.title)) && numOk(r.title, opts));
    const r30 = rows.filter((r) => days(r.date) <= 30), r90 = rows.filter((r) => days(r.date) <= 90), r365 = rows.filter((r) => days(r.date) <= 365);
    const last = rows.slice().sort((a, b) => b.date.localeCompare(a.date))[0] || null;
    let m = null, basis = null, n = 0;
    if (r30.length >= 3) { m = medianOf(r30.map((r) => r.price)); basis = "30d"; n = r30.length; }
    else if (r90.length >= 2) { m = medianOf(r90.map((r) => r.price)); basis = "90d"; n = r90.length; }
    // Oct 27 2026 (Mo: the high-end slabs trade a few times a year, "we should have it and not show it empty"): when neither
    // window marks, keep a 12-month median of >= 3 title-verified sales as its own labeled figure (m365) — never the mark.
    const m365 = n < 3 && r365.length >= 3 ? r2(medianOf(r365.map((r) => r.price))) : null;
    out[k] = { m: r2(m), basis, n, n365: r365.length, ...(m365 ? { m365 } : {}), last: last && days(last.date) <= 365 ? { d: last.date, p: r2(last.price) } : null };
  }
  return out;
}

function edOk(t, ed) {
  const first = /1st\s*ed|first\s*ed|\b1\.\s?ed/i.test(t), sl = /shadowless/i.test(t);   // "1.Edition" (German-style listing, NR01 #66 Oct 6)
  if (ed === "1st") return first;
  if (ed === "shadowless") return sl && !first;
  if (ed) return !first && !sl;
  return true;
}
// monthly price history for the card-page chart (Mo, Sep 30: "doesn't price charting show a chart we can use for individual
// cards?"). PriceCharting embeds VGPC.chart_data: used = ungraded, graded = Grade 9 (any grader), manualonly = PSA 10 — their
// monthly value estimate, the same series the index reconstructions use. Published as context, labelled as theirs, never as a mark.
export function histFromHtml(html, from = "2021-01") {
  const m = html.match(/VGPC\.chart_data\s*=\s*(\{[\s\S]*?\});/); if (!m) return null;
  let cd; try { cd = JSON.parse(m[1]); } catch (e) { return null; }
  const rows = new Map();
  for (const [k, i] of [["used", 1], ["graded", 2], ["manualonly", 3]]) for (const [ms, cents] of cd[k] || []) {
    const mo = new Date(ms + 12 * 3600e3).toISOString().slice(0, 7); if (mo < from || !cents) continue;
    if (!rows.has(mo)) rows.set(mo, [mo, null, null, null]);
    rows.get(mo)[i] = Math.round(cents) / 100;
  }
  return [...rows.values()].sort((x, y) => x[0].localeCompare(y[0]));
}
async function get(url) {
  for (let i = 1; i <= 4; i++) {
    const r = await fetch(url, { headers: { "User-Agent": UA }, redirect: "follow" });
    if (r.status === 429 || r.status === 403 || r.status >= 500) { await sleep(6000 * i); continue; }
    if (!r.ok) throw new Error("HTTP " + r.status);
    return await r.text();
  }
  throw new Error("rate limited after 4 attempts");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const IDX = JSON.parse(fs.readFileSync(path.join(ROOT, "data/indices.json"), "utf8"));
  const tks = (opt("--ticker", null) || POKEMON_SECTOR.concat(POKEMON_CHASE).join(",")).split(",").map((s) => s.trim()).filter(Boolean);
  const CACHE = opt("--cache", null); if (CACHE) fs.mkdirSync(CACHE, { recursive: true });
  const rd = (f) => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8")); } catch (e) { return null; } };
  const rawsOf = (tk) => { const m = new Map(); for (const b of (rd(`data/cards/${tk.toLowerCase()}.json`) || {}).cards || (IDX[tk] && IDX[tk].basket) || []) { const k = String(b.key || b.num); if (!m.has(k)) m.set(k, b.raw !== undefined ? b.raw : b.price); } return m; };
  const printHeld = (tk, held) => { for (const h of held) console.log(`  held ${tk} #${h.key} ${h.grade} ${h.why}: ${h.m != null ? "median $" + h.m : h.m365 != null ? "12-mo median $" + h.m365 : "lone sale"}${h.last ? " · last $" + h.last.p + " " + h.last.d : ""}`); };
  // --guard: re-apply the guards to the stored g-<tk>.json files (no reads, no new figures). Held cells stay held.
  if (args.includes("--guard")) {
    const DRY = args.includes("--dry"); let total = 0; const per = {};
    for (const tk of tks) {
      const f = `data/cards/g-${tk.toLowerCase()}.json`, doc = rd(f); if (!doc || !doc.cards) continue;
      const held = guardTicker(doc.cards, rawsOf(tk), ((rd(`data/cards/h-${tk.toLowerCase()}.json`) || {}).cards) || {});
      for (const h of held) per[h.why] = (per[h.why] || 0) + 1;
      total += held.length; printHeld(tk, held);
      const nHeld = Object.values(doc.cards).reduce((s, c) => s + ["psa9", "psa10", "tag10"].filter((k) => c && c[k] && c[k].held).length, 0);
      doc._comment = G_COMMENT; doc.guard = { v: GUARD.v, day: TODAY, held: nHeld };
      if (!DRY) fs.writeFileSync(path.join(ROOT, f), JSON.stringify(doc) + "\n");
    }
    console.log(`guard ${DRY ? "(dry) " : ""}${TODAY}: ${total} cell(s) newly held · ${JSON.stringify(per)}`);
    process.exit(0);
  }
  const jobs = [];
  const MISSING = args.includes("--missing");
  // KEY SAFETY (Oct 14 2026, Index Keeper — h-th26.json keys 4/25/33/106 charted the wrong card): a card key is assigned in
  // weight order (cardKey, lib/card-files.mjs), so when two cards that share a number swap rank, the bare key moves to the
  // other card. The g-/h- files now record each key's PriceCharting path (`paths`), and a previous row is carried into a
  // new file only when its key still points at the same card. Legacy rows (no `paths`) on a shared number are dropped.
  const curPaths = {}, sharedNum = {}, keyNum = {};
  for (const tk of tks) {
    let src = null; try { src = JSON.parse(fs.readFileSync(path.join(ROOT, `data/cards/${tk.toLowerCase()}.json`), "utf8")).cards; } catch (e) {}
    if (!src) src = (IDX[tk] && IDX[tk].basket) || [];
    let have = {}; if (MISSING) try { have = JSON.parse(fs.readFileSync(path.join(ROOT, `data/cards/g-${tk.toLowerCase()}.json`), "utf8")).cards || {}; } catch (e) {}
    const seen = new Set();
    curPaths[tk] = {}; keyNum[tk] = {}; const numCount = {};
    for (const b of src) { const k = String(b.key || b.num); if (b.path && !(k in curPaths[tk])) { curPaths[tk][k] = b.path; keyNum[tk][k] = String(b.num); } numCount[String(b.num)] = (numCount[String(b.num)] || 0) + 1; }
    sharedNum[tk] = new Set(Object.keys(numCount).filter((n) => numCount[n] > 1));
    // key = the card's key (num, or "<num>-<name>" for a second card on the same number — Classic Collection reprints), so two
    // cards never share one ladder (Oct 5 2026)
    // same-name cards on other numbers (TU19 Latias & Latios GX #113 / #170): a row naming the sibling's number is its sale
    const nm = (x) => String(x || "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim(), byName = {};
    for (const b of src) if (b.name != null) (byName[nm(b.name)] = byName[nm(b.name)] || new Set()).add(String(b.num));
    for (const b of src) { const num = String(b.key || b.num); if (!b.path || seen.has(num) || (MISSING && have[num])) continue; seen.add(num); jobs.push({ tk, num, path: b.path, opts: { num: String(b.num), siblings: [...(byName[nm(b.name)] || [])].filter((x) => x !== String(b.num)) } }); }
  }
  console.log(`ladder: ${jobs.length} card pages to read`);
  const LIMIT = +opt("--limit", 0); if (LIMIT) jobs.splice(LIMIT);
  // previous rows a new file may keep: the key must still point at the card it was read for (see KEY SAFETY above)
  function carryPrev(tk, doc) {
    const prev = (doc && doc.cards) || {}, pp = (doc && doc.paths) || null, cur = curPaths[tk] || {}, out = {};
    let dropped = 0;
    for (const [k, v] of Object.entries(prev)) {
      const ok = !cur[k] ? true : pp ? pp[k] === cur[k] : !sharedNum[tk].has(keyNum[tk][k]);
      if (ok) out[k] = v; else dropped++;
    }
    if (dropped) console.log(`${tk}: ${dropped} previous row(s) dropped — their key now points at a different card`);
    return out;
  }
  const cards = {}, hist = {}; let done = 0, errs = 0; const NOHIST = args.includes("--no-hist");
  async function worker() {
    while (jobs.length) {
      const j = jobs.shift(), key = `${j.tk}:${j.num}`, cf = CACHE && path.join(CACHE, key.replace(/[^A-Za-z0-9]+/g, "_") + ".json");
      try {
        if (cf && fs.existsSync(cf) && (NOHIST || fs.existsSync(cf.replace(/\.json$/, ".h.json")))) { cards[key] = JSON.parse(fs.readFileSync(cf, "utf8")); const hf = cf.replace(/\.json$/, ".h.json"); if (fs.existsSync(hf)) hist[key] = JSON.parse(fs.readFileSync(hf, "utf8")); }
        else {
          const html = await get("https://www.pricecharting.com/game/" + j.path);
          const l = ladderFromHtml(html, FIRST.has(j.tk) ? "1st" : SHADOWLESS.has(j.tk) ? "shadowless" : WOTC.has(j.tk), j.opts); l.asOf = TODAY; cards[key] = l;
          const hh = histFromHtml(html); if (hh) { hist[key] = hh; if (cf) fs.writeFileSync(cf.replace(/\.json$/, ".h.json"), JSON.stringify(hh)); }
          if (cf) fs.writeFileSync(cf, JSON.stringify(l));
          await sleep(PAUSE);
        }
      } catch (e) { errs++; console.error(key, e.message); }
      if (++done % 50 === 0) console.log(`  ${done} read · ${errs} errors`);
    }
  }
  await Promise.all(Array.from({ length: WORKERS }, worker));
  // one small file per ticker (a card page loads its own set only); a card that failed to read keeps its previous ladder
  for (const tk of tks) {
    const f = path.join(ROOT, `data/cards/g-${tk.toLowerCase()}.json`);
    let prevDoc = null; try { prevDoc = JSON.parse(fs.readFileSync(f, "utf8")); } catch (e) {}
    const prev = carryPrev(tk, prevDoc);
    const mine = { ...prev };
    let fresh = 0;
    const paths = { ...((prevDoc && prevDoc.paths) || {}) };
    for (const [k, v] of Object.entries(cards)) if (k.startsWith(tk + ":")) { const kk = k.slice(tk.length + 1); mine[kk] = v; if (curPaths[tk][kk]) paths[kk] = curPaths[tk][kk]; fresh++; }
    for (const k of Object.keys(paths)) if (!(k in mine)) delete paths[k];
    if (!fresh) continue;   // nothing read for this ticker: leave its file (and its read date) alone
    // guards (tools/lib/ladder-guard.mjs) on every row before it is written; PriceCharting's PSA 10 history = this read's, else the file's
    const hPrev = ((rd(`data/cards/h-${tk.toLowerCase()}.json`) || {}).cards) || {}, hNow = { ...hPrev };
    for (const [k, v] of Object.entries(hist)) if (k.startsWith(tk + ":")) hNow[k.slice(tk.length + 1)] = v;
    const heldNow = guardTicker(mine, rawsOf(tk), hNow); printHeld(tk, heldNow);
    const nHeld = Object.values(mine).reduce((s, c) => s + ["psa9", "psa10", "tag10"].filter((k) => c && c[k] && c[k].held).length, 0);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    // `day` is the ticker's last FULL read; a --missing run adds rows (each with its own asOf) without claiming one
    const day = MISSING && prevDoc && prevDoc.day ? prevDoc.day : TODAY;
    fs.writeFileSync(f, JSON.stringify({ _comment: G_COMMENT, ticker: tk, day, paths, guard: { v: GUARD.v, day: TODAY, held: nHeld }, cards: mine }) + "\n");
  }
  for (const tk of tks) {
    const fresh = {}; for (const [k, v] of Object.entries(hist)) if (k.startsWith(tk + ":")) fresh[k.slice(tk.length + 1)] = v;
    if (!Object.keys(fresh).length) continue;
    // merge onto the previous file: a --missing (or partly failed) run must not drop the histories it did not re-read
    let prevHDoc = null; try { prevHDoc = JSON.parse(fs.readFileSync(path.join(ROOT, `data/cards/h-${tk.toLowerCase()}.json`), "utf8")); } catch (e) {}
    const mine = { ...carryPrev(tk, prevHDoc), ...fresh };
    const paths = { ...((prevHDoc && prevHDoc.paths) || {}) };
    for (const k of Object.keys(fresh)) if (curPaths[tk][k]) paths[k] = curPaths[tk][k];
    for (const k of Object.keys(paths)) if (!(k in mine)) delete paths[k];
    fs.writeFileSync(path.join(ROOT, `data/cards/h-${tk.toLowerCase()}.json`), JSON.stringify({ _comment: "GENERATED by tools/build-card-ladder.mjs — PriceCharting's monthly price history per card (their value estimate, built from sales): [month, ungraded, Grade 9 any grader, PSA 10]. Chart context on /card, labelled as theirs; never a mark. paths = each key's PriceCharting item (key safety).", ticker: tk, day: TODAY, paths, cards: mine }) + "\n");
  }
  const v = Object.values(cards);
  console.log(`ladder ${TODAY}: ${v.length} cards · psa9 ${v.filter((c) => c.psa9 && c.psa9.m).length} · psa10 ${v.filter((c) => c.psa10 && c.psa10.m).length} · tag10 ${v.filter((c) => c.tag10 && (c.tag10.m || c.tag10.last)).length} · ${errs} errors`);
}
