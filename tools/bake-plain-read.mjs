#!/usr/bin/env node
// bake-plain-read.mjs — bakes "the plain read" into the six hand-authored Pokémon chase-index pages
// (Night Crew, Oct 4 2026 — backlog B36).
//
// Why: js/plain-read.js waits on /data/indices.json and then inserts the read above the chart and folds the stats
// block under it. On the chase pages that insert landed ~1 s after paint and pushed everything below it: production
// CLS 0.17 at 390 and 0.13 at 1024 on /prismatic-evolutions-index and /ascended-heroes-index (blocking plain-read.js
// took Prismatic to 0.000). The set-index pages got the same fix on Oct 3 inside build-sector-index.mjs (B29); the
// chase pages are hand-authored, so they get this small generator instead.
//
// What it writes, per page — nothing else is touched:
//   1. a PLAIN-READ block just above <div class="idx-chart" data-ticker="…">: the plain-read CSS (id="pr-css", so the
//      script does not inject it twice) and the box, from the SAME build()/bakeBox() the browser runs;
//   2. a hidden <div class="pr-fold" id="pr-fold-<tk>"> around the existing .stats + .statnote, exactly what the
//      script builds at runtime. The stats inside stay hand/remark-owned (remark-indices.mjs edits them in place).
// Every figure comes from data/indices.json, the file the script reads; no number is computed here. On load the
// script still refreshes the text if the data moved since the bake, and wires the button.
//
// When: tools/build-chase-strip.mjs runs this after its own bake, and remark-indices.mjs runs build-chase-strip after
// every chase re-mark, so the baked read moves with the marks. Safe to run any time; idempotent.
//
// Usage: node tools/bake-plain-read.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PR = createRequire(import.meta.url)(path.join(REPO, "js/plain-read.js"));
const CHECK = process.argv.includes("--check");

const PAGES = ["pitch-black-index", "chaos-rising-index", "ascended-heroes-index", "prismatic-evolutions-index", "destined-rivals-index", "phantasmal-flames-index"];
const START = "<!-- PLAIN-READ:START", END = "<!-- PLAIN-READ:END -->";
const FOLD_OPEN = "<!-- PLAIN-READ:FOLD -->", FOLD_CLOSE = "<!-- PLAIN-READ:FOLD-END -->";
const idx = JSON.parse(fs.readFileSync(path.join(REPO, "data/indices.json"), "utf8"));

function bake(html) {
  const m = /<div class="idx-chart" data-ticker="([A-Z0-9]+)"[^>]*><\/div>/.exec(html);
  if (!m) return { skip: "no chart" };
  const tk = m[1], r = idx[tk];
  if (!r || typeof r !== "object") return { skip: `${tk} not in indices.json` };
  const box = PR.bakeBox(tk, r);
  if (!box) return { skip: `${tk} has no read yet (pre-activation)` };
  const blk = `${START} — generated by tools/bake-plain-read.mjs from data/indices.json (js/plain-read.js build()). Do not hand-edit. -->\n<style id="pr-css">${PR.PR_CSS}</style>\n${box}\n${END}\n`;

  // 1 · the read above the chart
  if (html.includes(START)) {
    const a = html.indexOf(START), b = html.indexOf(END, a);
    if (b === -1) throw new Error("PLAIN-READ:START without END");
    html = html.slice(0, a) + blk + html.slice(b + END.length).replace(/^\n/, "");
  } else {
    const at = html.indexOf(m[0]);
    html = html.slice(0, at) + blk + html.slice(at);
  }

  // 2 · the fold around .stats + .statnote (once)
  if (!html.includes(FOLD_OPEN)) {
    const s = html.indexOf('<div class="stats">', html.indexOf(END));
    const n = s === -1 ? -1 : html.indexOf('<div class="statnote">', s);
    const e = n === -1 ? -1 : html.indexOf("</div>", n);
    if (e === -1) return { skip: `${tk} stats block not found`, html: null };
    const id = "pr-fold-" + tk.toLowerCase();
    html = html.slice(0, s) + `<div class="pr-fold" id="${id}" hidden>${FOLD_OPEN}\n` + html.slice(s, e + 6) + `\n${FOLD_CLOSE}</div>` + html.slice(e + 6);
  }
  return { tk, html };
}

const changed = [], skipped = [];
for (const slug of PAGES) {
  const f = path.join(REPO, slug + ".html");
  if (!fs.existsSync(f)) { skipped.push(`${slug} — not on disk`); continue; }
  const before = fs.readFileSync(f, "utf8");
  const out = bake(before);
  if (!out.html) { skipped.push(`${slug} — ${out.skip}`); continue; }
  if (out.html !== before) { changed.push(slug); if (!CHECK) fs.writeFileSync(f, out.html); }
}
console.log(`plain-read ${CHECK ? "check" : "bake"}: ${changed.length} page(s) ${CHECK ? "stale" : "updated"}${changed.length ? " — " + changed.join(", ") : ""}`);
for (const s of skipped) console.log("  skip " + s);
if (CHECK && changed.length) process.exit(1);
