#!/usr/bin/env node
/* build-worth-track.mjs — Q-072 (CoS handoff L-5, LEDGER O-129, Nov 27 2026).
   Puts the existing js/vault-track.js "★ Track" control under the first eBay
   button (div.hero-cta) of the worth guides, for the lead card the page prices.
   Name and set come from data/card-search.json (generated); no price is written
   (no data-price), so the Vault seeds nothing by hand.
   Owns the block <!-- WORTH:TRACK:START --> … <!-- WORTH:TRACK:END -->.
   Usage: node tools/build-worth-track.mjs [--check]   (--check: exit 1 if a page would change) */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PAGES = {
  "moonbreon-worth.html": "evs21-215",
  "charizard-ex-worth.html": "sv151-199",
  "gengar-ex-worth.html": "ah26-284",
  "mega-darkrai-ex-worth.html": "pb26-116",
  "van-gogh-pikachu-worth.html": "trk-svp85",
};
const VT_VER = 6; // same cache-bust as the card pages' /js/vault-track.js include

const check = process.argv.includes("--check");
const cards = JSON.parse(fs.readFileSync(path.join(ROOT, "data/card-search.json"), "utf8")).cards;
const byId = new Map(cards.map((c) => [c[0], c]));
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

let changed = 0;
for (const [file, id] of Object.entries(PAGES)) {
  const fp = path.join(ROOT, file);
  if (!fs.existsSync(fp)) { console.warn(`skip ${file}: missing`); continue; }
  const c = byId.get(id);
  if (!c) { console.warn(`skip ${file}: ${id} not in card-search.json`); continue; }
  const [, name, set] = c;
  const block =
    `<!-- WORTH:TRACK:START — Track control for the lead card, generated by tools/build-worth-track.mjs from data/card-search.json. Do not hand-edit. -->` +
    `<div class="worth-track" style="margin-top:10px;min-height:30px;">` +
    `<button type="button" class="sch-track-card" data-cid="${esc(id)}" data-name="${esc(name)} — ${esc(set)}" data-set="${esc(set)}" data-cat="pokemon" data-grade="Raw" title="Add this card to your watchlist">&#9733; Track this card</button>` +
    `</div><script src="/js/vault-track.js?v=${VT_VER}" defer></script>` +
    `<!-- WORTH:TRACK:END -->`;
  const raw = fs.readFileSync(fp, "utf8");
  let out;
  const re = /<!-- WORTH:TRACK:START[\s\S]*?<!-- WORTH:TRACK:END -->/;
  if (re.test(raw)) out = raw.replace(re, block);
  else {
    const m = raw.match(/^([ \t]*)<div class="hero-cta">.*<\/div>[ \t]*$/m);
    if (!m) { console.warn(`skip ${file}: no one-line div.hero-cta`); continue; }
    out = raw.replace(m[0], `${m[0]}\n${m[1]}${block}`);
  }
  if (out !== raw) {
    changed++;
    if (!check) fs.writeFileSync(fp, out);
    console.log(`${check ? "would update" : "updated"} ${file} (${id})`);
  }
}
console.log(`build-worth-track: ${changed} page(s) ${check ? "stale" : "changed"}`);
if (check && changed) process.exit(1);
