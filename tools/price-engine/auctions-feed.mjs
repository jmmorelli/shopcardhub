#!/usr/bin/env node
// tools/price-engine/auctions-feed.mjs — the Auction Desk SNAPSHOT (Oct 23 2026, the eBay budget fix).
//
// /api/auctions used to fan out 105 Browse calls on every CDN miss in every edge region — the whole 5k/day keyset
// quota on a busy day, and the homepage tile went dark at 16:37 PT on "eBay 429". Now the Action (auctions.yml, every
// 3 h) asks the function ONCE for a fresh answer and commits it as data/feed/auctions-latest.json; the function serves
// that snapshot (filtered to auctions still live) while it is fresh, in every region, for zero calls, and only fans out
// live when the snapshot has aged out and the budget allows (api/_lib/ebay-budget.js).
//
// Feed hygiene (R17/R19): listing titles and seller usernames are stripped before the write — the function fills the
// card's own label into the title slot when it serves a snapshot row. Never written when the answer is not a live
// fan-out, when it tripped on a 429 with nothing verified, or when more than half the cards errored: the previous
// snapshot stays, exactly like deals.yml.
//
//   node tools/price-engine/auctions-feed.mjs --out data/feed/auctions-latest.json
//   node tools/price-engine/auctions-feed.mjs --dry

import fs from "node:fs";
import path from "node:path";

const SITE = (process.env.SITE_URL || "https://www.shopcardhub.com").replace(/\/$/, "");
const args = process.argv.slice(2);
const arg = (k, d) => { const i = args.indexOf(k); return i >= 0 && args[i + 1] ? args[i + 1] : d; };
const OUT = arg("--out", "data/feed/auctions-latest.json");
const DRY = args.includes("--dry");

async function main() {
  const u = `${SITE}/api/auctions?fresh=1&t=${Date.now()}`;
  const r = await fetch(u, { headers: { Accept: "application/json", "x-shopcardhub-client": "tool" } });
  if (!r.ok) { console.error(`::error::/api/auctions -> HTTP ${r.status}; snapshot NOT written`); process.exit(1); }
  const d = await r.json();
  const cards = Array.isArray(d.cards) ? d.cards : [];
  const errored = cards.filter((c) => c.error).length;
  const summary = { source: d.source, generated: d.generated, cards: cards.length, errored, tripped: d.tripped || null, rows: (d.rows || []).length, verifiedCards: cards.filter((c) => c.verified > 0).length, quota: d.quota || null, note: d.note || null };
  console.log(JSON.stringify(summary));
  if (d.source !== "live") { console.error(`::error::answer was "${d.source}", not a live fan-out (${d.note || "budget"}); snapshot NOT written`); process.exit(1); }
  if (!cards.length || errored > cards.length / 2 || (d.tripped && !(d.rows || []).length)) { console.error(`::error::${errored}/${cards.length} cards errored${d.tripped ? " (" + d.tripped + ")" : ""}; snapshot NOT written`); process.exit(1); }
  const rows = (d.rows || []).map(({ title: _t, seller, ...row }) => ({ ...row, seller: seller ? { feedbackPct: seller.feedbackPct ?? null, feedbackScore: seller.feedbackScore ?? null } : null }));
  const feed = {
    _comment: "GENERATED by tools/price-engine/auctions-feed.mjs from /api/auctions (live fan-out) — verified live eBay auctions for every tracked card, with the nightly ask-basis mark and watched hammers beside each. No listing titles or seller names (R17). /api/auctions serves this while fresh and drops ended rows itself.",
    generated: d.generated, day: String(d.generated || "").slice(0, 10), source: "snapshot",
    basis: d.basis, markDay: d.markDay || null, customId: d.customId || "auctions",
    affiliateTagged: rows.some((x) => x.url && x.url.includes("mkevt=")),
    cards: cards.map((c) => ({ id: c.id, label: c.label, mark: c.mark ?? null, hammerMedian: c.hammerMedian ?? null, scanned: c.scanned ?? 0, verified: c.verified ?? 0, rejected: c.rejected ?? 0, error: c.error || null })),
    count: rows.length, underMark: rows.filter((x) => x.vsMark != null && x.vsMark < 0).length,
    quota: d.quota || null, rows,
  };
  if (DRY) { console.log("--dry: not written"); return; }
  fs.mkdirSync(path.dirname(path.resolve(OUT)), { recursive: true });
  fs.writeFileSync(path.resolve(OUT), JSON.stringify(feed, null, 1));
  console.log(`wrote ${OUT} (${rows.length} rows, ${feed.cards.length} cards, ${errored} errored)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
