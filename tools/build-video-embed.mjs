#!/usr/bin/env node
// build-video-embed.mjs — the YouTube release-breakdown tile on an index page (CoS, Nov 2 2026; YouTube lane,
// Project claude/youtube/CHARTER.md).
//
// Driven by data/videos.json:
//   { "<page>.html": [ { "id": "<youtubeId>", "title": "...", "date": "YYYY-MM-DD", "kind": "breakdown" } ] }
// Writes one block per listed page between <!-- VIDEO:START --> / <!-- VIDEO:END -->. Idempotent: an existing block
// is replaced in place (it never moves); a missing one is inserted directly UNDER the index block (chart + plain read
// + method + stats, i.e. after the page's <!-- <TK>:END --> marker and any signup capture sitting right under it), so
// everything that follows (breaks, engine blocks, guide folds, related links, footer) stays below the tile. Never
// above the fold, never above the chart (R11 / R43 chart-first order hold; the block adds nothing to the first screen).
//
// The tile: 12 px eyebrow · the video title as a tile headline · a lazy 16:9 youtube-nocookie <iframe> · a one-line
// dated caption · a .ds-more link to the channel. No JS of its own, no tracking, no fonts: the iframe is the only
// third-party request and it is lazy (nothing loads until the tile scrolls near the viewport). CSS is additive under
// the .sch-video namespace and reads DESIGN-SYSTEM.md tokens (--ds-*) with page-var fallbacks; no global token is set.
//
// Usage: node tools/build-video-embed.mjs [--check]     (--check: exit 1 if any page would change; writes nothing)
// Re-run whenever data/videos.json changes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const START = "<!-- VIDEO:START";
const START_FULL = "<!-- VIDEO:START — release breakdown video. Generated by tools/build-video-embed.mjs from data/videos.json. Do not hand-edit. -->";
const END = "<!-- VIDEO:END -->";
const CHANNEL = "https://www.youtube.com/@ShopCardHub";

const CSS = `<style id="sch-video-css">
.sch-video{max-width:1060px;margin:22px auto 0;padding:0 var(--ds-gutter,24px);box-sizing:border-box}
.sch-video-tile{background:var(--ds-surface-2,var(--bg3,#1d1d1f));border-radius:var(--ds-radius,18px);padding:24px;overflow:hidden}
.sch-video-eyebrow{font:400 var(--ds-fs-cap,12px)/1.33 var(--ds-font,system-ui,sans-serif);letter-spacing:.02em;color:var(--text-dim,#a1a1a6);margin:0 0 6px}
.sch-video-h{font:600 var(--ds-fs-tile,24px)/1.17 var(--ds-font,system-ui,sans-serif);color:var(--text-head,#f5f5f7);margin:0 0 16px;text-transform:none;letter-spacing:0}
.sch-video-frame{position:relative;width:100%;aspect-ratio:16/9;background:#000;border-radius:10px;overflow:hidden}
.sch-video-frame iframe{position:absolute;inset:0;width:100%;height:100%;border:0;display:block}
@supports not (aspect-ratio:16/9){.sch-video-frame{height:0;padding-bottom:56.25%}}
.sch-video-cap{font:400 var(--ds-fs-2,14px)/1.43 var(--ds-font,system-ui,sans-serif);color:var(--text-dim,#a1a1a6);margin:12px 0 0}
.sch-video-more{display:inline-block;margin-top:8px;font:400 var(--ds-fs-2,14px)/1.43 var(--ds-font,system-ui,sans-serif)}
@media(max-width:734px){.sch-video-tile{padding:20px}}
</style>`;

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const fmtDate = (iso) => { const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso || ""); return m ? `${MONTHS[+m[2] - 1]} ${+m[3]}, ${m[1]}` : esc(iso || ""); };
const KIND = { breakdown: "Release breakdown" };

function videoTile(v) {
  if (!/^[A-Za-z0-9_-]{6,20}$/.test(v.id || "")) throw new Error(`bad YouTube id: ${JSON.stringify(v.id)}`);
  if (!v.title) throw new Error(`video ${v.id} has no title`);
  const eyebrow = KIND[v.kind] || KIND.breakdown;
  return `<div class="sch-video-tile">
  <p class="sch-video-eyebrow">${esc(eyebrow)}</p>
  <h2 class="sch-video-h">${esc(v.title)}</h2>
  <div class="sch-video-frame"><iframe src="https://www.youtube-nocookie.com/embed/${v.id}" title="${esc(v.title)}" loading="lazy" allow="accelerometer; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen referrerpolicy="strict-origin-when-cross-origin"></iframe></div>
  <p class="sch-video-cap">Published ${fmtDate(v.date)} on the ShopCardHub YouTube channel. The numbers in the video are the marks of its recording date; the index above is the live read.</p>
  <a class="ds-more sch-video-more" href="${CHANNEL}" target="_blank" rel="noopener">More breakdowns on the ShopCardHub YouTube channel</a>
</div>`;
}

function block(videos) {
  return `${START_FULL}\n${CSS}\n<section class="sch-video" id="video" aria-label="Release breakdown video">\n${videos.map(videoTile).join("\n")}\n</section>\n${END}`;
}

// Where a NEW block goes: directly under the index block — right after its <!-- TK:END --> marker (the last
// <!-- TK:START --> above the chart names TK), and after a SIGNUP capture when build-signup.mjs put one immediately
// under that block (BCB26). So on BCB26 the tile sits between the signup and the BREAKS section; on the 30th page
// between TH26:END and the DEST strip. Everything below (breaks, engine blocks, guide folds, related, footer) stays
// below it. A page with no chart, or no END marker below its chart, is skipped and named (never guessed).
function insertionPoint(html) {
  const chart = html.indexOf('class="idx-chart"');
  if (chart === -1) return -1;
  const starts = [...html.slice(0, chart).matchAll(/<!-- ([A-Z0-9]+):START -->/g)];
  if (!starts.length) return -1;
  const endTag = `<!-- ${starts[starts.length - 1][1]}:END -->`;
  const e = html.indexOf(endTag, chart);
  if (e === -1) return -1;
  let at = e + endTag.length;
  const m = /^\s*<!-- SIGNUP:START[\s\S]*?<!-- SIGNUP:END -->/.exec(html.slice(at));
  if (m) at += m[0].length;
  // start the block on its own line
  const nl = html.indexOf("\n", at);
  return nl === -1 ? html.length : nl + 1;
}

const cfgPath = path.join(REPO, "data/videos.json");
const cfg = JSON.parse(fs.readFileSync(cfgPath, "utf8"));
const changed = [], same = [], skipped = [];
for (const [page, videos] of Object.entries(cfg)) {
  const file = path.join(REPO, page);
  if (!fs.existsSync(file)) { skipped.push(`${page}: no such page`); continue; }
  if (!Array.isArray(videos) || !videos.length) { skipped.push(`${page}: no videos listed`); continue; }
  const html = fs.readFileSync(file, "utf8");
  const b = block(videos);
  let out;
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s !== -1 && e !== -1 && e > s) {
    out = html.slice(0, s) + b + html.slice(e + END.length);
  } else if (s !== -1 || e !== -1) {
    skipped.push(`${page}: half a VIDEO block (one marker only) — fix by hand`); continue;
  } else {
    const at = insertionPoint(html);
    if (at === -1) { skipped.push(`${page}: no anchor below the chart (BREAKS block or <footer>)`); continue; }
    out = html.slice(0, at) + b + "\n" + html.slice(at);
  }
  if (out === html) { same.push(page); continue; }
  changed.push(page);
  if (!CHECK) fs.writeFileSync(file, out);
}
console.log(`build-video-embed: ${CHECK ? "would change" : "wrote"} ${changed.length} page(s)${changed.length ? " — " + changed.join(", ") : ""}; unchanged ${same.length}; skipped ${skipped.length}`);
for (const s of skipped) console.log("  skip: " + s);
if (CHECK && changed.length) process.exit(1);
