// tools/lib/local-nav.mjs — the card-page local nav (Cupertino run 9, Nov 8 2026; R46, DESIGN-SYSTEM.md "Local nav").
// One builder for both writers, so they print the same bytes:
//   · tools/build-card-template.mjs puts the block in every static /card-<slug> page it writes;
//   · tools/build-local-nav.mjs re-stamps it on the card pages already on disk (and the set-index pages, its own block).
//
// The bar: the card's name on the left (back to the top), Chart · Sales · Grades (the page's own tabs; desktop only), and
// ONE pill on the right. The pill's href, target and rel are the page's baked raw eBay link (the "Raw copies on eBay" link
// in <div id="cdp-load">, built by build-card-template.mjs through tools/lib/epn.mjs), copied byte for byte: so the search,
// the customid (card-<id>) and every EPN parameter are that link's. Its words are the page's own main button's default,
// "Buy Raw on eBay", so it never says less than where it goes. No script rides in the block: js/card-page.js opens the
// tabs (it listens on .lnav[data-lnav-card]) and loads the scroll flow after it renders.
export const LNAV_START = "<!-- LOCALNAV:START", LNAV_END = "<!-- LOCALNAV:END -->";

// the first EPN link inside the stub (#cdp-load), raw attribute text as written in the file
export function stubRawLink(html) {
  const i = html.indexOf('id="cdp-load"');
  if (i === -1) return null;
  const z = html.indexOf("</div>", i);
  const stub = html.slice(i, z === -1 ? undefined : z);
  const a = /<a\b([^>]*?)\bhref="(https:\/\/www\.ebay\.com\/[^"]*campid=5339155990[^"]*)"([^>]*)>/.exec(stub);
  if (!a) return null;
  const attr = (k) => { const r = new RegExp(`\\b${k}="([^"]*)"`).exec(a[1] + " " + a[3]); return r ? r[1] : null; };
  return { href: a[2], target: attr("target"), rel: attr("rel") };
}

// the card's name as the stub's <h1> prints it (already HTML-escaped by the template)
export function stubName(html) {
  const i = html.indexOf('id="cdp-load"');
  const m = i === -1 ? null : /<h1>([^<]+)<\/h1>/.exec(html.slice(i, i + 2000));
  return m ? m[1] : null;
}

// id: the card id on <main data-card-id> (e.g. pris25-161); nameHtml: escaped name; link: from stubRawLink()
export function cardLocalNav(id, nameHtml, link) {
  const tk = String(id).split("-")[0].toUpperCase();
  const tgt = link.target ? ` target="${link.target}"` : "";
  const rel = link.rel ? ` rel="${link.rel}"` : "";
  const tabs = [["chart", "Chart"], ["sales", "Sales"], ["grades", "Grades"]]
    .map(([k, l]) => `<a href="#cdp-tab-${k}" data-tab="${k}">${l}</a>`).join("");
  return `${LNAV_START} — sticky local nav, card page (Cupertino run 9, Nov 8 2026; DESIGN-SYSTEM.md "Local nav"). Generated by tools/lib/local-nav.mjs (build-card-template.mjs, build-local-nav.mjs); the pill's link is this page's own raw eBay link, copied byte for byte. Do not hand-edit. -->
<div class="lnav lnav-card" data-lnav-card="${id}"><div class="lnav-in">
<a class="lnav-t" href="#cdp">${nameHtml}</a>
<div class="lnav-l" role="navigation" aria-label="On this page">${tabs}</div>
<a class="lnav-pill" href="${link.href}"${tgt}${rel} aria-label="Buy Raw on eBay: ${nameHtml}" onclick="if(typeof gtag==='function')gtag('event','localnav_click',{tk:'${tk}',card:'${id}',page:location.pathname})">Buy Raw on eBay</a>
</div></div>
${LNAV_END}`;
}

// put the block right after NAV:END (or replace the one there); returns the new html, or null when the page has no NAV:END
export function placeLocalNav(html, block) {
  const a = html.indexOf(LNAV_START);
  if (a !== -1) {
    const z = html.indexOf(LNAV_END, a);
    if (z === -1) throw new Error(`${LNAV_START} without END`);
    return html.slice(0, a) + block + html.slice(z + LNAV_END.length);
  }
  const nav = html.indexOf("<!-- NAV:END -->");
  if (nav === -1) return null;
  const at = nav + "<!-- NAV:END -->".length;
  return html.slice(0, at) + "\n" + block + html.slice(at);
}

// ── The breadcrumb (Cupertino run 10, Nov 9 2026; DESIGN-SYSTEM.md "Navigation → Breadcrumb") ──────────────────────
// Plain words in sentence case, "›" between steps, the page itself last and unlinked: "Set indices › Destined Rivals".
// Was "RESEARCH / SET INDICES / DR25" (caps, a step that links nowhere, the ticker for a name). One builder for every
// writer: tools/build-local-nav.mjs (the set-index pages, re-stamped on each run), the page scaffolders and the
// checklist / class-ladder generators. trail: [[label, href], …, [label]]; labels arrive HTML-escaped. Look: site-fixes §0c.
export function crumbHtml(trail, style) {
  const steps = trail.map(([label, href], i) => (i === trail.length - 1 && !href)
    ? `<span aria-current="page">${label}</span>`
    : `<a href="${href}">${label}</a>`);
  return `<nav class="crumb"${style ? ` style="${style}"` : ""} aria-label="Breadcrumb">${steps.join('<span class="sep" aria-hidden="true"> › </span>')}</nav>`;
}

// replace the page's set-index crumb (the first <div|nav class="crumb"> after NAV:END that links to /indices), keeping
// its inline style; returns the new html, or null when the page has no such crumb (named by the caller, never guessed)
export function placeCrumb(html, trail) {
  const from = Math.max(0, html.indexOf("<!-- NAV:END -->"));
  const re = /<(div|nav) class="crumb"([^>]*)>([\s\S]*?)<\/\1>/g;
  re.lastIndex = from;
  const m = re.exec(html);
  if (!m || !m[3].includes('href="/indices"')) return null;
  const st = /\bstyle="([^"]*)"/.exec(m[2]);
  return html.slice(0, m.index) + crumbHtml(trail, st ? st[1] : null) + html.slice(m.index + m[0].length);
}
