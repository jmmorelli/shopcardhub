#!/usr/bin/env node
// build-break-math.mjs — PLAYER BREAK MATH on a Bowman cohort page (Sep 30 2026, idea #45; Mo: "do it, i approve").
//
// A player break sells one prospect's slot in a case: the buyer gets every card of that player the case yields.
// What the slot is worth in autographs is arithmetic we already have the inputs for:
//   expected autos of player P per case, by parallel  = packs per case / (pack odds x checklist size)
//   value of each                                    = P's base-auto sold mark x the tier multiple (data/tiers.json)
// Assumptions, printed on the page: every player on the checklist is seeded equally (Topps publishes no per-player
// odds); unnumbered-to-/35 parallels are counted at 1x base (a floor — they sell above base); /99-/5 use the BOW26
// serial tier ladder's pooled multiples; SuperFractors and non-auto cards are left out. The figure is an expected
// value, not a price and not a mark (R20): no spot price is shown, and nothing here tells anyone to buy.
// Links: guarded eBay searches for that player's break spots (auctions included), customid <tk>-break-<slug>, shown
// only where production /api/comps finds >= 3 spot listings naming the player (--links file from the desk's check).
// Usage: node tools/build-break-math.mjs --ticker BCB26 [--top 15] [--links links.json] [--dry]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ebaySearchUrl, SACAT_SPORTS, assertClean } from "./lib/epn.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const TK = opt("--ticker", "BCB26"), TOP = +opt("--top", 15), DRY = args.includes("--dry");
const J = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8"));
const IDX = J("data/indices.json"), ODDS = J("data/break-odds.json")[TK], TIERS = (J("data/tiers.json").BOW26 || {}).tiers || {};
if (!ODDS) throw new Error("no odds for " + TK);
const LINKS = opt("--links") ? JSON.parse(fs.readFileSync(opt("--links"), "utf8")) : null;
const esc = (s) => String(s == null ? "" : s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const usd = (x) => "$" + x.toFixed(2);
const mdy = (d) => { const p = String(d).slice(0, 10).split("-"); return `${p[1]}/${p[2]}/${p[0].slice(2)}`; };
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const packs = ODDS.packsPerBox * ODDS.boxesPerCase, N = ODDS.checklist;
const perPlayer = {}; let autos = 0;
for (const o of ODDS.odds) { if (o.tier === "1") continue; const e = packs / o.packs / N; perPlayer[o.tier] = (perPlayer[o.tier] || 0) + e; autos += e; }
const mult = (t) => (t === "base" || t === "numbered-high") ? 1 : (TIERS[t] && TIERS[t].mult) || 1;
const evMult = Object.entries(perPlayer).reduce((a, [t, e]) => a + e * mult(t), 0);   // expected auto value per case, in units of the player's base mark
const casesPerAuto = 1 / autos;

const x = IDX[TK];
const rows = x.basket.filter((b) => /^CPA/i.test(b.num) && b.price > 0).sort((a, b) => b.price - a.price).slice(0, TOP);
const asOf = rows.reduce((a, b) => (b.asOf > a ? b.asOf : a), "");
const tr = rows.map((b) => {
  const ok = !LINKS || (LINKS[b.name] || 0) >= 3;
  const url = ok ? assertClean(ebaySearchUrl({ q: `${b.name} 2026 bowman chrome break`, customid: `${TK.toLowerCase()}-break-${slug(b.name)}`, sacat: SACAT_SPORTS, bin: false })) : null;
  return `<tr><td class="bm-n"><b>${esc(b.name)}</b><small>${esc(b.num)}</small></td><td><span class="roi-price">${usd(b.price)}</span><small>sold mark · ${mdy(b.asOf)}</small></td><td class="bm-ev"><b>${usd(b.price * evMult)}</b><small>autos per case, expected</small></td><td class="act">${url ? `<a class="auc" href="${url}" target="_blank" rel="sponsored nofollow noopener" data-evt="break_click">Break spots →</a>` : `<span class="bm-na">few spots listed</span>`}</td></tr>`;
}).join("\n");
const all = assertClean(ebaySearchUrl({ q: "2026 bowman chrome player break", customid: `${TK.toLowerCase()}-break-all`, sacat: SACAT_SPORTS, bin: false }));
const t = (k) => (TIERS[k] && TIERS[k].mult ? TIERS[k].mult.toFixed(1) + "×" : "1×");

const block = `<!-- BREAKS:${TK}:START — generated by tools/build-break-math.mjs from data/break-odds.json + data/indices.json + data/tiers.json. Do not hand-edit. -->
<style id="bm-css">
.bm{margin:22px 0 0;border:1px solid var(--border,rgba(255,255,255,.08));background:var(--bg2,#0c1017);padding:16px 16px 12px;font-family:var(--fb,Barlow,system-ui,sans-serif);color:var(--text,#b8cdd4)}
.bm-eyebrow{font-family:var(--fm,ui-monospace,monospace);font-size:10px;letter-spacing:3px;text-transform:uppercase;color:var(--gold,#f5c800)}
.bm h2{font-family:var(--fd,'Barlow Condensed',sans-serif);font-size:clamp(22px,3vw,30px);font-weight:900;text-transform:uppercase;color:var(--text-head,#e4f0f4);margin:6px 0 6px;line-height:1.05}
.bm p{font-size:13px;line-height:1.55;margin:0 0 10px;max-width:700px;color:var(--text-dim,#7a969e)}
.bm p b{color:var(--text-head,#e4f0f4)}
.bm-wrap{overflow-x:auto}
.bm table{width:100%;border-collapse:collapse;font-family:var(--fm,ui-monospace,monospace);font-size:12.5px;min-width:560px}
.bm th{font-size:9px;letter-spacing:2px;text-transform:uppercase;color:var(--text-dim,#7a969e);text-align:left;padding:8px 10px;border-bottom:1px solid var(--border,rgba(255,255,255,.08));font-weight:400}
.bm td{padding:9px 10px;border-bottom:1px solid var(--border,rgba(255,255,255,.06));vertical-align:middle}
.bm td small{display:block;font-size:9.5px;color:var(--text-dim,#7a969e);margin-top:2px}
.bm-n b{color:var(--text-head,#e4f0f4);font-family:var(--fd,'Barlow Condensed',sans-serif);font-size:15px}
.bm-ev b{font-size:15px;color:var(--gold,#f5c800)}
.bm .roi-price{font-weight:700}
.bm-na{color:var(--text-dim,#7a969e);font-size:11px}
.bm a.auc{display:inline-block;font-size:10px;font-weight:700;letter-spacing:1.3px;text-transform:uppercase;color:#000;background:var(--gold,#f5c800);padding:7px 10px;border-radius:2px;text-decoration:none;white-space:nowrap;min-height:30px;line-height:16px}
.bm-f{font-family:var(--fm,ui-monospace,monospace);font-size:9.5px;color:var(--text-dim,#7a969e);margin-top:10px;line-height:1.6}
.bm-f a{color:var(--accent,#00ccf5)}
</style>
<section class="bm" id="breaks" data-prices-updated="${asOf}">
<div class="bm-eyebrow">Player break math · ${esc(ODDS.product)}</div>
<h2>What a player spot holds in autos</h2>
<p>In a player break you buy one prospect's slot and get every card of his that the case yields. A 12-box case holds about <b>${(autos * N).toFixed(1)}</b> Chrome Prospect Autographs across ${N} players, so any one player averages <b>${autos.toFixed(2)} autos per case</b>, about one every ${casesPerAuto.toFixed(1)} cases. Priced at his own sold mark, with numbered parallels at the tier ladder's multiples, that is <b>${evMult.toFixed(2)}× his base-auto mark per case</b>. A spot that costs more than the figure below is paying for base cards, refractors and the long shot.</p>
<div class="bm-wrap"><table>
<thead><tr><th>Player</th><th>Base auto</th><th>Expected auto value / case</th><th></th></tr></thead>
<tbody>
${tr}
</tbody></table></div>
<p style="margin-top:12px"><a class="auc" href="${all}" target="_blank" rel="sponsored nofollow noopener" data-evt="break_click" style="display:inline-block;font-family:var(--fm,ui-monospace,monospace);font-size:10px;font-weight:700;letter-spacing:1.3px;text-transform:uppercase;color:#000;background:var(--gold,#f5c800);padding:7px 10px;border-radius:2px;text-decoration:none">All 2026 Bowman Chrome player break spots →</a></p>
<div class="bm-f">Odds: Topps' hobby pack odds for Chrome Prospect Autographs (${packs} packs per case; odds sheet as printed by <a href="${esc(ODDS.source)}" target="_blank" rel="noopener">Checklist Insider</a>, read ${mdy(ODDS.read)}). Assumes every one of the ${N} players is seeded equally — Topps publishes no per-player odds. Parallels unnumbered to /35 counted at 1× base (a floor); /99 ${t("99")} · /50 ${t("50")} · /25 ${t("25")} · /10 ${t("10")} · /5 ${t("5")} from the <a href="/bowman-1st-chrome-index#tiers">serial tier ladder</a>; SuperFractors and non-auto cards left out. Base marks are 30-day sold medians. An expected value, not a price. Break links are eBay searches (affiliate links); eBay limits breaks to its pre-approved sellers.</div>
</section>
<!-- BREAKS:${TK}:END -->`;

const file = path.join(ROOT, x.page.replace(/^\//, "") + ".html");
let h = fs.readFileSync(file, "utf8");
const re = new RegExp(`<!-- BREAKS:${TK}:START[\\s\\S]*?<!-- BREAKS:${TK}:END -->`);
if (re.test(h)) h = h.replace(re, block);
else { const end = `<!-- ${TK}:END -->`; if (!h.includes(end)) throw new Error("no " + end); h = h.replace(end, end + "\n" + block); }
if (!DRY) fs.writeFileSync(file, h);
console.log(`${TK}: autos/player/case ${autos.toFixed(3)} (1 in ${casesPerAuto.toFixed(1)} cases) · EV ${evMult.toFixed(3)}x base · rows ${rows.length} · links ${rows.filter((b) => !LINKS || (LINKS[b.name] || 0) >= 3).length}`);
